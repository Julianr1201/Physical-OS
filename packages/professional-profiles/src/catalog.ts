import { parseManifest, type ProfileManifest } from './schema.js';

const disclosure = {
  en: 'I am an AI professional, not a person.',
  es: 'Soy un profesional de inteligencia artificial, no una persona.',
};

const metrics = ['turns', 'handoffs', 'denied', 'checkouts'] as const;

interface Seed {
  profileId: string;
  industry: string;
  profession: string;
  specialization: string;
  displayName: { en: string; es: string };
  description: { en: string; es: string };
  purpose: string;
  capabilities: string[];
  knowledgeSources: string[];
  tools: Array<{ id: string; effect: 'read' | 'propose' | 'checkout' | 'handoff' | 'teach' }>;
  requiredPermissions: string[];
  safetyPolicies: string[];
  presencePreset: string;
  voicePreset: string;
  cues: string[];
  target: string;
  formality: 'casual' | 'professional' | 'formal';
  pace: 'calm' | 'measured' | 'brisk';
  greeting: { en: string; es: string };
}

function seed(input: Seed): ProfileManifest {
  return parseManifest({
    schemaVersion: 1,
    version: '1.0.0',
    profileId: input.profileId,
    industry: input.industry,
    profession: input.profession,
    specialization: input.specialization,
    displayName: input.displayName,
    description: input.description,
    purpose: input.purpose,
    capabilities: input.capabilities,
    knowledgeSources: input.knowledgeSources,
    tools: input.tools,
    requiredPermissions: input.requiredPermissions,
    safetyPolicies: input.safetyPolicies,
    presencePreset: input.presencePreset,
    voicePreset: input.voicePreset,
    supportedLanguages: ['en', 'es'],
    handoffPolicy: { cues: input.cues, target: input.target },
    deploymentRequirements: { simulated: true, integrations: input.knowledgeSources },
    tone: { formality: input.formality, pace: input.pace, greeting: input.greeting },
    disclosure,
    metrics: [...metrics],
  });
}

